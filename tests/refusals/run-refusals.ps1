#!/usr/bin/env pwsh
# §3.B refusal gate (E2E wave 2, G33): every refused construct must FAIL LOUDLY and NEVER miscompile.
#
# For each fixture we assert the PRD §3.B contract end to end:
#   * `polyglot build` exits nonzero,
#   * it prints a `<path>:<line>:<col>: error:` shaped diagnostic (the editor-parseable shape the
#     watch gate and the VS Code problemMatcher also freeze),
#   * the message NAMES the refusal (not a generic "unknown type"), and
#   * NO output file is written — a stale pre-seeded twin keeps its sentinel byte-for-byte and the
#     out dir gains nothing (a refused compile is all-or-nothing, never a partial emit).
#
# Plus the `polyglot check` surface: good -> exit 0, broken -> nonzero, `--json` field shape, and the
# `--json --watch` incompatibility (exit 64).
#
# Usage:  pwsh tests/refusals/run-refusals.ps1   (build the solution first; see CLAUDE.md)

param(
    [string]$Cli = "$PSScriptRoot\..\..\x64\Debug\MintPlayer.Polyglot.Cli.exe"
)

$ErrorActionPreference = "Stop"

if (-not (Test-Path $Cli)) {
    Write-Host "polyglot CLI not found at $Cli - build the solution first (see CLAUDE.md)."
    exit 2
}

$fixtures = Join-Path $PSScriptRoot "fixtures"
# The C# target's ownership header line, read from the plugin manifest (the single source of truth).
$csManifest = Join-Path $PSScriptRoot "..\..\plugins\csharp\polyglot-plugin.json"
$csHeader = ([regex]::Match((Get-Content -Raw $csManifest), '"line":\s*"(//\s*Generated by Polyglot\.[^"]*)"')).Groups[1].Value
if (-not $csHeader) { Write-Host "cannot find the C# header line in $csManifest"; exit 2 }
# A diagnostic line, editor-parseable: `<path>:<line>:<col>: <severity>: <message>`. Searched as a
# substring so a leading Windows drive letter (`C:\`) never trips it (a drive colon is followed by `\`).
$reDiag = ':\d+:\d+: (error|warning|info): '

$bad = 0
function Assert([bool]$cond, [string]$name) {
    if ($cond) { Write-Host "[PASS] $name" } else { Write-Host "[FAIL] $name"; $script:bad++ }
}

# Per-run unique temp root so a crashed previous run can't poison this one.
$work = Join-Path ([System.IO.Path]::GetTempPath()) ("polyglot-refusals-" + [guid]::NewGuid().ToString("N").Substring(0, 8))
New-Item -ItemType Directory -Force $work | Out-Null

# Run `build <fixture> --target csharp --out <fresh dir>` with a stale sentinel twin pre-seeded, and
# return the merged output + whether the sentinel survived + the post-build file count.
function Invoke-RefusedBuild([string]$fixtureName) {
    $src = Join-Path $fixtures $fixtureName
    $stem = [System.IO.Path]::GetFileNameWithoutExtension($fixtureName)
    $out = Join-Path $work ($stem + "-out")
    Remove-Item -Recurse -Force $out -ErrorAction SilentlyContinue
    New-Item -ItemType Directory -Force $out | Out-Null
    # The sentinel carries the C# target's ownership header LINE, so the overwrite guard (P40 D18) would let
    # a build replace it: "the twin is untouched" then really observes that the refused build wrote nothing.
    # Without the header the guard refuses the overwrite on its own and the check passes vacuously (review r3).
    # The positive control below (a GOOD fixture through this same function) proves the seed is overwritable.
    $sentinel = "$csHeader`nSTALE-SENTINEL-$stem-DO-NOT-TOUCH`n"
    $twin = Join-Path $out ($stem + ".cs")
    [System.IO.File]::WriteAllText($twin, $sentinel)
    $output = & $Cli build $src --target csharp --out $out 2>&1 | Out-String
    $code = $LASTEXITCODE
    $twinAfter = if (Test-Path -LiteralPath $twin) { [System.IO.File]::ReadAllText($twin) } else { $null }
    $fileCount = @(Get-ChildItem -LiteralPath $out -File).Count
    return [pscustomobject]@{
        Output = $output; Exit = $code
        SentinelKept = ($twinAfter -ceq $sentinel); FileCount = $fileCount
    }
}

# Literal (ordinal, case-sensitive) substring test — `-like "*$frag*"` treats ? [ ] * as wildcards and
# ignores case, so a fragment could match text it does not spell.
function Has([string]$text, [string]$frag) { return $text.Contains($frag, [System.StringComparison]::Ordinal) }

# fixture -> ASCII message fragments the diagnostic must contain. ($null would mean a raw-parse-error
# fixture asserting only nonzero exit + no output — none remain: #54 gave the finalizer a targeted message.)
$cases = [ordered]@{
    "lock_stmt.pg"              = @("refuses threads and locks")
    "unsafe_block.pg"           = @("no unsafe blocks")
    "thread_type.pg"            = @("refuses threads and locks")
    "decimal_type.pg"           = @("refuses 'decimal'")
    "activator_type.pg"         = @("refuses runtime reflection")
    "dynamic_type.pg"           = @("refuses 'dynamic'")
    "await_outside_async.pg"    = @("'await' is only allowed inside an 'async fn'")
    "empty_list_uninferable.pg" = @("cannot infer the type of 'xs'")
    "null_var_uninferable.pg"   = @("cannot infer the type of 'x'")
    "finalizer.pg"              = @("refuses finalizers")
    "block_match_arm.pg"        = @("block-bodied match arm")
    "namespace_import.pg"       = @("namespace import")
    "is_union.pg"               = @("union types/cases", "use 'match'")
    "implicit_conversion.pg"    = @("refuses implicit user conversions")
    "meta_typeparam.pg"         = @("cannot be a type parameter")
    "unknown_escape.pg"         = @("unknown escape sequence", "valid escapes are")
    "astral_char.pg"            = @("an astral character", "one UTF-16 code unit")
    "multi_char_literal.pg"     = @("more than one character", "use a string")
    "range_operand.pg"          = @("a range ('a..b') is only valid as a for-loop iterable")
    "range_let.pg"              = @("a range ('a..b') is only valid as a for-loop iterable")
    "float_range.pg"            = @("range bounds must be integers (got f64)")
    "super_method.pg"           = @("'super' is only supported as a base-constructor call", "'super.m()'")
    "super_value.pg"            = @("'super' is only supported as a base-constructor call")
    "throw_match_arm.pg"        = @("'throw' is a statement, not an expression")
    "nullable_concat.pg"        = @("'+' operand of type 'string?' may be null", "supply a fallback with '??' or assert with '!'")
    "nullable_hole.pg"          = @("interpolation hole of type 'i32?' may be null")
    "nullable_compare.pg"       = @("'<' operand of type 'i32?' may be null")
    "string_plus_typeparam.pg"  = @("'string + T' concatenates a type parameter", "interpolate instead")
    "nullable_compound.pg"      = @("'+=' target 'n' of type 'i32?' may be null")
    "nullable_member.pg"        = @("'.v' on a receiver of type 'Box?', which may be null", "use '?.v'")
    "record_in_hole.pg"         = @("cannot interpolate a value of type 'P'", "format the value explicitly")
    "list_in_hole.pg"           = @("cannot interpolate a value of type 'List<i32>'")
    "enum_in_hole.pg"           = @("cannot interpolate a value of type 'Color'", "an enum has no portable text")
    "enum_in_print.pg"          = @("print cannot print a value of type 'Color'", "map it to a string explicitly")
    "class_bound_explicit.pg"   = @("type argument 'string' of 'NumBox' does not satisfy the bound 'T: INumber'")
    "class_bound_inferred.pg"   = @("type argument 'string' of 'NumBox' does not satisfy the bound 'T: INumber'")
    "class_bound_interface.pg"  = @("type argument 'i32' of 'Ladder' does not satisfy the bound 'T: Ranked'")
    "extension_default_nonliteral.pg" = @("the default of 'by' in extension 'i32.shifted' must be a literal")
    "extern_nullable_typeparam.pg" = @("'Shelf.find' yields 'V?' while 'V' is still a type parameter")
    "module_scope_leak.pg"      = @("'List' is declared in module 'std.collections', which this module does not import", 'import "std.collections"')
    "std_reserved_prefix.pg"    = @("'__pgCharAt' uses a prefix reserved for the Polyglot std library")
    "unreachable_code.pg"       = @("unreachable code", "remove it")
    "missing_return.pg"         = @("function 'sign' can reach the end of its body without returning a value")
    "lambda_missing_return.pg"  = @("this lambda can reach the end of its body without returning a value")
    "static_let_assign.pg"      = @("cannot assign to immutable static field 'Limits.Max'", "declare it 'static var'")
    "field_one_branch.pg"       = @("field 'name' of class 'Cfg' is not assigned on every path through init")
    "field_early_return.pg"     = @("returns before field 'b' is assigned")
    "ctor_open_call.pg"         = @("the constructor of class 'Widget' calls the overridable method 'describe' on 'this'")
    "ctor_open_call_indirect.pg" = @("the constructor of class 'Base' calls the overridable method 'describe' on 'this' (through 'announce')")
    "static_hides_instance.pg"  = @("'label' redeclares the static member 'Base.label' as an instance member", "no member hiding")
    "static_hides_static.pg"    = @("'count' redeclares the static member 'B.count' as a static member", "CS0108")
    "default_non_finite.pg"     = @("the default of 'x' in function 'huge' is not a finite number")
    "self_compare.pg"           = @("compares a value with itself", "Math.isNaN")
    "eq_without_hash.pg"        = @("'Money' declares a custom", "equal values must hash equally")
    "unknown_operator.pg"       = @("'frob' is not an operator")
}

foreach ($fx in $cases.Keys) {
    $r = Invoke-RefusedBuild $fx
    Assert ($r.Exit -ne 0) "$fx : build exits nonzero"
    Assert ($r.Output -cmatch $reDiag) "$fx : prints a path:line:col: error: diagnostic"
    $frags = $cases[$fx]
    if ($null -ne $frags) {
        foreach ($frag in $frags) {
            Assert (Has $r.Output $frag) "$fx : diagnostic names the refusal ($frag)"
        }
    }
    Assert $r.SentinelKept "$fx : the stale pre-seeded twin is untouched (no overwrite)"
    Assert ($r.FileCount -eq 1) "$fx : no output file written (out dir holds only the pre-seed)"
}

# --- positive control: the seeded sentinel IS overwritable, so the sentinel checks above can fail ---------
# A good program through the same seeding must replace the twin. Were the seed refused by the overwrite guard
# (a missing or wrong header line), every "untouched" check above would pass without observing anything.
$ctrl = Invoke-RefusedBuild "good.pg"
Assert ($ctrl.Exit -eq 0) "control good.pg : build exits 0 (output: $($ctrl.Output.Trim()))"
Assert (-not $ctrl.SentinelKept) "control good.pg : the header-carrying seed is overwritten (sentinel checks are live)"

# --- the 3-error fixture: every position is reported, not just the first ------------------------------
$three = Invoke-RefusedBuild "three_errors.pg"
$diagLines = @($three.Output -split "`r?`n" | Where-Object { $_ -cmatch $reDiag })
Assert ($diagLines.Count -ge 3) "three_errors.pg : all three diagnostics reported (got $($diagLines.Count))"
Assert ((Has $three.Output "refuses threads and locks") -and
        (Has $three.Output "refuses runtime reflection") -and
        (Has $three.Output "refuses 'decimal'")) `
    "three_errors.pg : each of the three distinct refusals is named"
# The three diagnostics sit on lines 3, 4, 5 of the fixture (after the 2-line header comment).
$linesReported = @($diagLines | ForEach-Object { if ($_ -cmatch ':(\d+):\d+: error:') { [int]$Matches[1] } } | Sort-Object -Unique)
Assert (($linesReported -contains 3) -and ($linesReported -contains 4) -and ($linesReported -contains 5)) `
    "three_errors.pg : the three error positions are on distinct lines 3/4/5"

# --- polyglot check: good exits 0, broken exits nonzero -----------------------------------------------
$good = Join-Path $fixtures "good.pg"
& $Cli check $good *> $null
Assert ($LASTEXITCODE -eq 0) "check <good.pg> exits 0"
$broken = Join-Path $fixtures "three_errors.pg"
& $Cli check $broken *> $null
Assert ($LASTEXITCODE -ne 0) "check <broken.pg> exits nonzero"

# --- check --json: a machine-readable array with line/col/message per diagnostic ----------------------
# (Probed: `check --help`/`build --help` document --json as a line/col/severity/message array. There is
# NO `file` field — check is single-file, so the path is implicit; asserted below and noted in the summary.)
$jsonRaw = & $Cli check $broken --json 2>&1 | Out-String
Assert ($LASTEXITCODE -ne 0) "check --json on a broken file still exits nonzero"
$parsed = $null
try { $parsed = $jsonRaw | ConvertFrom-Json } catch { }
Assert ($null -ne $parsed) "check --json emits parseable JSON"
if ($null -ne $parsed) {
    $arr = @($parsed)
    Assert ($arr.Count -ge 3) "check --json is an array with all diagnostics ($($arr.Count))"
    $d0 = $arr[0]
    $hasLine = $null -ne $d0.PSObject.Properties['line']
    $hasCol = $null -ne $d0.PSObject.Properties['col']
    $hasMsg = $null -ne $d0.PSObject.Properties['message']
    Assert ($hasLine -and $hasCol -and $hasMsg) "check --json elements carry line/col/message fields"
    Assert (($d0.line -is [int]) -or ($d0.line -is [long])) "check --json 'line' is numeric"
    Assert (-not [string]::IsNullOrEmpty([string]$d0.message)) "check --json 'message' is non-empty"
}
# check --json on the good file: an empty array, exit 0.
$goodJson = & $Cli check $good --json 2>&1 | Out-String
Assert ($LASTEXITCODE -eq 0 -and $goodJson.Trim() -eq "[]") "check --json on a clean file is '[]' with exit 0"

# --- --json + --watch are mutually exclusive (exit 64, the CLI-usage code) ----------------------------
$jw = & $Cli check $broken --json --watch 2>&1 | Out-String
Assert ($LASTEXITCODE -eq 64 -and $jw -cmatch 'cannot be combined') "check --json --watch is refused with exit 64"

Remove-Item -Recurse -Force $work -ErrorAction SilentlyContinue

Write-Host ""
if ($bad -eq 0) {
    Write-Host "Refusal gate green: every refused construct fails loudly and writes no output."
    exit 0
}
Write-Host "$bad refusal-gate assertion(s) failed."
exit 1
