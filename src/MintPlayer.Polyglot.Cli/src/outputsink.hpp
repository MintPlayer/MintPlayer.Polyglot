// Polyglot's ownership key. `<auto-generated/>` alone is NOT enough: Roslyn generators, NSwag, OpenAPI
// Generator and protoc plugins all emit it, and their files may sit in the same folders (D5).
inline constexpr const char* kGeneratedMarker = "Generated by Polyglot.";

inline bool carriesGeneratedLine(const std::filesystem::path& p, int maxLines = 5) {
    std::ifstream in(p, std::ios::binary);
    if (!in) return false;
    std::string line;
    for (int i = 0; i < maxLines && std::getline(in, line); ++i)
        if (line.find(kGeneratedMarker) != std::string::npos) return true;
    return false;
}

// One identity per output file, whatever spelling routed to it ("obj/x/../a.cs", a relative --out, a
// different-case drive letter that weakly_canonical folds).
inline std::string outputKey(const std::filesystem::path& p) {
    std::error_code ec;
    std::filesystem::path c = std::filesystem::weakly_canonical(p, ec);
    return (ec ? std::filesystem::absolute(p, ec).lexically_normal() : c).generic_string();
}

class OutputSink {
public:
    enum class Mode { Write, Check };
    explicit OutputSink(Mode mode = Mode::Write) : mode_(mode) {}
    bool checking() const { return mode_ == Mode::Check; }

    enum class Put { Written, Unchanged, Deduped, Conflict, Failed };

    // Produce one file. A path produced earlier in the RUN with identical content is a no-op (a shared
    // module reached from several roots); different content is a conflict, never a silent clobber — across
    // config groups too. Write mode is write-if-changed (an unchanged twin keeps its mtime, so a dev server
    // watching it does not churn); Check mode compares against disk and records drift.
    Put put(const std::filesystem::path& out, const std::string& content) {
        const std::string key = outputKey(out);
        if (auto it = produced_.find(key); it != produced_.end())
            return it->second == content ? Put::Deduped : Put::Conflict;
        produced_[key] = content;
        std::string existing;
        const bool exists = readFile(out, existing);
        if (exists && existing == content) {
            if (!checking()) std::cout << "  -> " << out.string() << "\n";
            return Put::Unchanged;
        }
        if (checking()) {
            drift_.insert(std::string("polyglot: would ") + (exists ? "update " : "create ") + out.string());
            return Put::Written;
        }
        if (!writeFile(out, content)) return Put::Failed;
        std::cout << "  -> " << out.string() << "\n";
        return Put::Written;
    }

    bool isProduced(const std::filesystem::path& p) const { return produced_.count(outputKey(p)) != 0; }

    // Delete (Write) or report (Check). The CALLER has already applied the deletion invariant above.
    bool remove(const std::filesystem::path& p, const char* why) {
        if (checking()) {
            drift_.insert("polyglot: would delete " + p.string());
            return true;
        }
        std::error_code ec;
        if (!std::filesystem::remove(p, ec) || ec) {
            std::cerr << "polyglot: cannot delete '" << p.string() << "'\n";
            return false;
        }
        std::cout << "  x  " << p.string() << " (" << why << ")\n";
        return true;
    }

    bool drifted() const { return !drift_.empty(); }
    // Sorted, so CI logs diff cleanly.
    std::vector<std::string> driftLines() const { return {drift_.begin(), drift_.end()}; }

private:
    Mode mode_;
    std::map<std::string, std::string> produced_; // outputKey -> content, run-wide
    std::set<std::string> drift_;
};

// ---- the outputs record --------------------------------------------------------------------------------

struct RecordOutput {
    std::string path; // relative to the record's directory, '/'-separated (absolute when on another root)
    std::string map;  // the sidecar, same form; empty = none
};
struct RecordSection {
    std::vector<std::string> inputs;
    std::vector<RecordOutput> outputs;
};
struct OutputsRecord {
    std::map<std::string, RecordSection> sections; // "<configDir>|<target>" -> section
};

inline constexpr int kOutputsRecordVersion = 1;

enum class RecordLoad { Ok, Missing, Corrupt, Newer };

inline RecordLoad loadOutputsRecord(const std::filesystem::path& file, OutputsRecord& rec) {
    rec = {};
    std::string src;
    if (!readFile(file, src)) return RecordLoad::Missing;
    const json::Value v = json::parse(src);
    if (v.kind != json::Value::Kind::Object || v["version"].kind != json::Value::Kind::Number ||
        v["sections"].kind != json::Value::Kind::Object)
        return RecordLoad::Corrupt;
    if (v["version"].asInt() > kOutputsRecordVersion) return RecordLoad::Newer;
    if (v["version"].asInt() != kOutputsRecordVersion) return RecordLoad::Corrupt;
    for (const auto& [key, sv] : v["sections"].members) {
        if (sv.kind != json::Value::Kind::Object) return RecordLoad::Corrupt;
        RecordSection s;
        for (const auto& i : sv["inputs"].items())
            if (i.kind == json::Value::Kind::String) s.inputs.push_back(i.asString());
        for (const auto& o : sv["outputs"].items()) {
            if (o["path"].kind != json::Value::Kind::String) return RecordLoad::Corrupt;
            s.outputs.push_back({o["path"].asString(), o["map"].asString()});
        }
        rec.sections[key] = std::move(s);
    }
    return RecordLoad::Ok;
}

// A path as the record stores it: relative to `recordDir` when it can be, '/'-separated.
inline std::string recordRelative(const std::filesystem::path& p, const std::filesystem::path& recordDir) {
    const std::filesystem::path a = absoluteDir(p);
    const std::filesystem::path rel = a.lexically_relative(absoluteDir(recordDir));
    return rel.empty() ? a.generic_string() : rel.generic_string();
}
inline std::filesystem::path recordResolve(const std::string& stored, const std::filesystem::path& recordDir) {
    const std::filesystem::path p(stored);
    return (p.is_absolute() ? p : absoluteDir(recordDir) / p).lexically_normal();
}

inline std::string serializeOutputsRecord(const OutputsRecord& rec) {
    std::string out = "{\n  \"version\": " + std::to_string(kOutputsRecordVersion) + ",\n  \"sections\": {";
    bool firstSec = true;
    for (const auto& [key, s] : rec.sections) {
        out += firstSec ? "\n" : ",\n";
        firstSec = false;
        out += "    " + json::quote(key) + ": {\n      \"inputs\": [";
        for (std::size_t i = 0; i < s.inputs.size(); ++i) out += (i ? ", " : "") + json::quote(s.inputs[i]);
        out += "],\n      \"outputs\": [";
        for (std::size_t i = 0; i < s.outputs.size(); ++i) {
            out += i ? ",\n        " : "\n        ";
            out += "{\"path\": " + json::quote(s.outputs[i].path);
            if (!s.outputs[i].map.empty()) out += ", \"map\": " + json::quote(s.outputs[i].map);
            out += "}";
        }
        out += s.outputs.empty() ? "]\n    }" : "\n      ]\n    }";
    }
    out += firstSec ? "}\n}\n" : "\n  }\n}\n";
    return out;
}

// Temp file + rename, so a crash mid-write leaves the previous record, never half of one.
inline bool saveOutputsRecord(const std::filesystem::path& file, const OutputsRecord& rec) {
    const std::string doc = serializeOutputsRecord(rec);
    std::string existing;
    if (readFile(file, existing) && existing == doc) return true;
    std::filesystem::path tmp = file;
    tmp += ".tmp";
    if (!writeFile(tmp, doc)) return false;
    std::error_code ec;
    std::filesystem::rename(tmp, file, ec);
    if (ec) {
        std::filesystem::remove(tmp, ec);
        return false;
    }
    return true;
}

// The record's section key: the config's directory relative to the record ("" when no config), plus the
// target. One section per (config group, target), so `--only` replaces exactly the targets it built.
inline std::string recordSectionKey(bool configFound, const std::filesystem::path& configDir,
                                    const std::string& target, const std::filesystem::path& recordDir) {
    return (configFound ? recordRelative(configDir, recordDir) : std::string()) + "|" + target;
}

// ---- the depfile ---------------------------------------------------------------------------------------

inline bool writeDepfile(const std::filesystem::path& file, const std::set<std::string>& deps) {
    std::string doc;
    for (const auto& d : deps) doc += d + "\n";
    std::string existing;
    if (readFile(file, existing) && existing == doc) return true; // MSBuild compares mtimes: don't churn
    return writeFile(file, doc);
}

// ---- owned scopes --------------------------------------------------------------------------------------

struct OwnedScope {
    std::filesystem::path dir; // absolute
    bool recursive = false;
    std::string ext;           // the built target's file extension (".ts")
    std::string sidecarExt;    // its origin sidecar extension (".map"), "" = none
};

// The literal output-folder prefix of one owned rule's template: everything before the first `%(`, cut
// back to the last '/'. Recursive when what follows can introduce directories (`%(RecursiveDir)`,
// `%(Directory)`, or any later '/', e.g. `gen/%(TargetLanguage)/%(Filename)`).
inline void ownedPrefix(const std::string& tmpl, std::string& dir, bool& recursive) {
    const std::size_t ph = tmpl.find("%(");
    const std::string lit = tmpl.substr(0, ph);
    const std::size_t slash = lit.rfind('/');
    dir = slash == std::string::npos ? std::string() : lit.substr(0, slash);
    const std::string rest = ph == std::string::npos ? std::string() : tmpl.substr(ph);
    recursive = rest.find("%(RecursiveDir)") != std::string::npos ||
                rest.find("%(Directory)") != std::string::npos || rest.find('/') != std::string::npos;
}

// Every file in scope that this run did not produce. Dot-dirs and the usual dependency/output trees are
// pruned below the scope root (the discovery precedent).
template <class IsProduced>
std::vector<std::filesystem::path> ownedExtras(const OwnedScope& s, IsProduced isProduced) {
    namespace fs = std::filesystem;
    std::vector<fs::path> found;
    std::error_code ec;
    if (!fs::is_directory(s.dir, ec)) return found;
    auto consider = [&](const fs::directory_entry& e) {
        std::error_code tec;
        if (!e.is_regular_file(tec)) return;
        const std::string name = e.path().filename().string();
        if (name.size() <= s.ext.size() || name.compare(name.size() - s.ext.size(), s.ext.size(), s.ext) != 0)
            return;
        if (!isProduced(e.path())) found.push_back(e.path());
    };
    if (s.recursive) {
        fs::recursive_directory_iterator it(s.dir, fs::directory_options::skip_permission_denied, ec), end;
        for (; !ec && it != end; it.increment(ec)) {
            std::error_code tec;
            const std::string name = it->path().filename().string();
            if (it->is_directory(tec)) {
                if (!name.empty() && (name[0] == '.' || name == "node_modules" || name == "bin" || name == "obj"))
                    it.disable_recursion_pending();
                continue;
            }
            consider(*it);
        }
    } else {
        for (fs::directory_iterator it(s.dir, ec), end; !ec && it != end; it.increment(ec)) consider(*it);
    }
    std::sort(found.begin(), found.end());
    return found;
}

