#pragma once

// P40 B5 + D17 — everything the CLI writes, and everything it may delete, goes through this header.
//
//  * OutputSink — the ONE writer behind every write path (multi-root build, single build, watch, source
//    maps). It owns the run-wide produced-path set, so a path two config groups both route to is an error
//    instead of a silent overwrite, and it has a Check mode (`build --check`) that writes nothing and
//    records drift (`would create|update|delete`) instead.
//  * The outputs RECORD (`{version:1, sections:{"<configDir>|<target>": {inputs, outputs:[{path, map?}]}}}`)
//    — what an authoritative run produced, so the next run can delete "previous minus current". Paths are
//    relative to the record's own directory, so a copied repository never deletes in the original.
//  * The DEPFILE — one absolute path per line (configs, lockfiles, every .pg of every closure, `file:`
//    plugin manifests) for MSBuild's Inputs.
//  * Owned scopes — the literal output folder of an `"owned": true` include rule.
//
// THE DELETION INVARIANT (PRD §B5 + D17, D20) — stated once, enforced by the callers of `remove`:
//   1. exactly two deletion paths: the record's doomed set, and the owned-prefix extras;
//   2. both require the file to carry `Generated by Polyglot.` (kGeneratedMarker) in its first 5 lines;
//   3. a file without that line is never deleted, by either path;
//   4. any failed group in a run means nothing is deleted.
// A `.map` sidecar cannot carry a comment line; it is deleted only together with its (marked) owner.

