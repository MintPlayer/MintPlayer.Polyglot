// P40 B5 + D17 — everything the CLI writes, and everything it may delete, goes through this header.
//
//  * OutputSink — the ONE writer behind every write path (multi-root build, single build, watch, source
//    maps). It owns the run-wide produced-path set, so a path two config groups both route to is an error
//    instead of a silent overwrite, and it has a Check mode (`build --check`) that writes nothing and
//    records drift (`would create|update|delete`) instead.
//  * The outputs RECORD (`{version:1, sections:{"<configDir>|<target>": {inputs, outputs:[{path, map?}]}}}`)
//    — what an authoritative run produced, so the next run can delete "previous minus current". Paths are
//    relative to the record's own directory, so a copied repository never deletes in the original.
//  * The DEPFILE — one absolute path per line (configs, lockfiles, every .pg of every closure, `file:`
//    plugin manifests) for MSBuild's Inputs.
//  * Owned scopes — the literal output folder of an `"owned": true` include rule.
//
// THE DELETION INVARIANT (PRD §B5 + D17, D20) — stated once, enforced by the callers of `remove`:
//   1. exactly three deletion paths: the record's doomed set, the owned-prefix extras, and the stale temp
//      files of this run's own outputs (`sweepStaleTemps`: `<output>.pgtmp.<n>.<n>.<n>` / `<output>.pgcase.tmp`,
//      older than ten minutes);
//   2. all three require the file to carry Polyglot's header LINE — `<lineComment> Generated by Polyglot.`, the
//      target's own comment token from its plugin manifest — as one of its first 5 lines (a line that
//      merely MENTIONS the phrase does not count: P40 review, #75); a map temp instead names its owner as `file`;
//   3. a file without that line is never deleted, by any path;
//   4. any failed group in a run means nothing is deleted — the temp sweep included (P40 review r5: it used to
//      run inside `put`, so an exit-1 build still deleted a stale temp; it is now deferred to the run's end).
// A `.map` sidecar cannot carry a comment line; it is deleted only together with its (marked) owner, at the
// path DERIVED from the owner (`owner + sidecarExtension`, never a path read from the record), and only when
// it is a source map naming that owner as its `file` (isOwnSidecar).
//
// THE OVERWRITE GUARD (P40 review, #75 — D21): `put` never replaces an existing file whose bytes differ unless
// it is Polyglot's: it carries the header line (a sidecar: names its owner), or the outputs record lists it,
// or it sits under a build-owned directory the caller declared (`--build-owned`, MSBuild's obj/ dir), or the
// run adopts unmarked outputs (`--adopt`, the one-time upgrade path for 0.10.x outputs, which had no header).
// Anything else is Refused: exit 1, the file untouched — and under --check an error, not `would update`.

